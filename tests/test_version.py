def test_failed_generated_write_leaves_the_source_and_copies_intact(
    project: Path, monkeypatch: pytest.MonkeyPatch,
) -> None:
    before = contents(project)
    original_file = tempfile.NamedTemporaryFile
    writes = 0

    def temporary_file(*args: Any, **kwargs: Any) -> Any:
        nonlocal writes
        stream = original_file(*args, **kwargs)
        writes += 1
        if writes == 2:
            def fail_write(_text: str) -> None:
                raise OSError(28, 'No space left on device')
            monkeypatch.setattr(stream, 'write', fail_write)
        return stream

    monkeypatch.setattr(tempfile, 'NamedTemporaryFile', temporary_file)
    with pytest.raises(OSError, match='No space left'):
        sync_version(project, '2.0.0')
    assert contents(project) == before


def test_standalone_command_works_outside_the_checkout(project: Path, tmp_path: Path) -> None:
    scripts = project / 'scripts'
    scripts.mkdir()
    script = scripts / 'version.py'
    shutil.copy2(ROOT / 'scripts/version.py', script)

    def invoke(*arguments: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run([sys.executable, str(script), *arguments], cwd=tmp_path.parent,
                              capture_output=True, encoding='utf-8', check=False)

    stale = invoke('--check')
    assert stale.returncode == 1
    assert 'Cargo.toml' in stale.stderr
    assert invoke('2.0.0').returncode == 0
    checked = invoke('--check')
    assert checked.returncode == 0
    assert checked.stdout == '2.0.0\n'
    assert not checked.stderr
    assert read_version(project) == '2.0.0'
    before = contents(project)
    invalid = invoke('3.0.0', '--check')
    assert invalid.returncode == 2
    assert contents(project) == before
